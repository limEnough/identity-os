export interface PracticeOption {
  action: string;
  caption: string;
}

/** 실천 카드를 그 사람의 여정에 붙이는 재료 — 없으면 일반형 문장으로 물러난다 */
export interface PracticeContext {
  /** 동경의 축약 표현 (ENVY.short) */
  envy?: string;
  /** 부러움이 찾아오는 순간 (MomentOption.phrase) */
  moment?: string;
}

/** 가치 하나를 이번 주의 작은 행동들로 번역한다 — 고르는 건 언제나 사용자다 */
export function buildPractices(
  value: string,
  ctx: PracticeContext = {},
): PracticeOption[] {
  const options: PracticeOption[] = [
    {
      action: `${DIRECTION[value] ?? '나의 문장대로 하루를 산다'} — 이번 주 한 번`,
      caption: '아주 작게, 그러나 분명하게',
    },
    {
      action: RITUAL[value] ?? `「${value}」${iga(value)} 드러난 순간 하나를 적어두기`,
      caption: '생각보다 몸이 먼저 알아차려요',
    },
    {
      action: `「${value}」${iga(value)} 무너졌던 순간을 하루 끝에 한 줄로 적기`,
      caption: '판단 없이, 기록만',
    },
  ];

  if (ctx.moment) {
    options.push({
      action: `${ctx.moment} — 그때 「${value}」${eul(value)} 한 번 떠올리기`,
      caption: '가장 흔들리는 자리에 이름을 하나 세워두기',
    });
  }

  options.push({
    action: ctx.envy
      ? `부러웠던 그 사람의 ${ctx.envy}${eul(ctx.envy)} 오늘 하루만 빌려 쓰기`
      : '부러웠던 그 사람이 할 법한 일을 딱 하나 해보기',
    caption: '동경을 흉내가 아닌 실험으로',
  });

  return options;
}
